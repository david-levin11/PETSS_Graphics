#!/usr/bin/env python3
"""
Download PETSS station CSV tarballs from NOMADS, extract one station CSV,
load it into pandas, and plot total water level (TWL).

This version integrates with a generated PETSS station-map config file,
for example one produced by build_petss_station_map.py:

    python build_petss_station_map.py --latest --regions nwak --output-py petss_station_map.py

Then run the TWL plotter with station-name matching:

    python petss_csv_twl_plotter_integrated.py --location "Nome" --region nwak --outdir petss_data

Or refresh the station map from the latest PETSS storm tide text file before plotting:

    python petss_csv_twl_plotter_integrated.py --location "Nome" --region nwak --refresh-station-map

Direct station ID still works and bypasses station-name lookup:

    python petss_csv_twl_plotter_integrated.py --date 20260622 --cycle 06 --station-id 9468756 --outdir petss_data

Notes:
- NOMADS CSV tarball pattern:
  https://nomads.ncep.noaa.gov/pub/data/nccf/com/petss/prod/petss.YYYYMMDD/petss.tHHz.csv.tar.gz
- Extracted archive path commonly looks like:
  petss.tHHz.csv/petss.YYYYMMDD/tHHz.csv/<station_id>.csv
- PETSS CSV missing values are usually 9999.000.
"""

